    /**
     * 多维加权匹配算法：
     * - 标题完全匹配：100分
     * - 标题前缀匹配：80分
     * - 标题包含匹配：60分
     * - 关键词包含匹配：40分
     * - 描述包含匹配：25分
     * - 面包屑路径匹配：20分
     * - 分类名称包含匹配：10分
     */
    fun search(query: String): List<SettingsSearchItem> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return allItems

        // 拆分子词（支持空格分割的多词搜索）
        val subQueries = trimmed.split("\\s+".toRegex()).filter { it.isNotEmpty() }

        return allItems
            .mapNotNull { item ->
                var score = 0
                val titleLower = item.title.lowercase()
                val subtitleLower = item.subtitle.lowercase()
                val categoryLower = item.category.label.lowercase()
                val breadcrumbLower = item.breadcrumb?.lowercase().orEmpty()

                // 优先全词匹配
                if (titleLower == trimmed) {
                    score += 100
                } else if (titleLower.startsWith(trimmed)) {
                    score += 80
                } else if (titleLower.contains(trimmed)) {
                    score += 60
                }

                if (item.keywords.any { it.lowercase().contains(trimmed) }) {
                    score += 40
                }

                if (subtitleLower.contains(trimmed)) {
                    score += 25
                }

                if (breadcrumbLower.contains(trimmed)) {
                    score += 20
                }

                if (categoryLower.contains(trimmed)) {
                    score += 10
                }

                // 如果多词搜索，检查各子词的命中情况
                if (subQueries.size > 1) {
                    val allMatched = subQueries.all { sub ->
                        titleLower.contains(sub) ||
                        subtitleLower.contains(sub) ||
                        breadcrumbLower.contains(sub) ||
                        item.keywords.any { it.lowercase().contains(sub) }
                    }
                    if (allMatched) {
                        score += 50
                    }
                }

                if (score > 0) item to score else null
            }
            .sortedByDescending { it.second }
            .map { it.first }
    }
